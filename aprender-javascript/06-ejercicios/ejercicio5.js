/*

Ejercicio 5

Tengo una tarta de queso con 16 porciones.
Cada porción vale 3.8 euros.
¿Si vendo todas las porciones cuanto dinero gano en total?

*/

const porciones = 16;

let precio = 3.8;

let resultado = porciones * precio;

console.log("Si vendes todas las porciones de la tarta de queso, ganarás: " + resultado + " euros");
